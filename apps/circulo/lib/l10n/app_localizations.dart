import 'package:flutter/material.dart';

class AppLocalizations {
  final Locale locale;

  AppLocalizations(this.locale);

  static const List<Locale> supportedLocales = [
    Locale('es'),
    Locale('en'),
    Locale('pt'),
    Locale('fr'),
    Locale('it'),
    Locale('de'),
  ];

  static const LocalizationsDelegate<AppLocalizations> delegate =
      _AppLocalizationsDelegate();

  static AppLocalizations of(BuildContext context) {
    return Localizations.of<AppLocalizations>(context, AppLocalizations) ??
        AppLocalizations(const Locale('es'));
  }

  static Locale resolveLocale(Locale? deviceLocale, [String? savedCode]) {
    if (savedCode != null && savedCode != 'auto') {
      return Locale(savedCode);
    }
    if (deviceLocale == null) return const Locale('es');
    final code = deviceLocale.languageCode.toLowerCase();
    for (final supported in supportedLocales) {
      if (supported.languageCode == code) return supported;
    }
    return const Locale('es');
  }

  String get langCode => locale.languageCode;

  String get(String key) {
    final lang = _localizedValues.containsKey(langCode) ? langCode : 'es';
    return _localizedValues[lang]?[key] ??
        _localizedValues['es']?[key] ??
        key;
  }

  // Traducción dinámica con parámetros
  String format(String key, Map<String, dynamic> params) {
    String text = get(key);
    params.forEach((k, v) {
      text = text.replaceAll('{$k}', v.toString());
    });
    return text;
  }

  // Helpers de catálogos
  String translateInterest(String key) {
    return get('interest_$key');
  }

  String translatePlan(String key) {
    return get('plan_$key');
  }

  String translateVibe(String key) {
    return get('vibe_$key');
  }

  String translateAvailability(String key) {
    return get('slot_$key');
  }

  String translateGroupRole(String roleKey) {
    switch (roleKey) {
      case 'organizer':
        return get('roleOrganizer');
      case 'connector':
        return get('roleConnector');
      case 'explorer':
        return get('roleExplorer');
      case 'chill':
      default:
        return get('roleChill');
    }
  }

